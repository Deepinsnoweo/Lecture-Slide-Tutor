"""Quiz report export — generates a self-contained Markdown file from a
QuizSet, QuizResult, and optional WeaknessReport."""

from __future__ import annotations

from slide_tutor.models import QuizResult, QuizSet, WeaknessReport
from slide_tutor.quiz_formatting import format_quiz_answer, question_by_id, quiz_result_icon


def _format_points(value: float | int | None) -> str:
    if value is None:
        return "—"
    value = float(value)
    if value.is_integer():
        return str(int(value))
    return f"{value:.1f}"


def _question_type_label(question_type: str) -> str:
    return {
        "mcq": "MCQ",
        "true_false": "True/False",
        "fill_blank": "Fill Blank",
        "short_answer": "Short Answer",
    }.get(question_type, question_type)


def _correct_answer_label(question_type: str) -> str:
    if question_type == "fill_blank":
        return "Expected answer"
    if question_type == "short_answer":
        return "Model answer"
    return "Correct option"


def export_quiz_report_markdown(
    quiz_set: QuizSet | None = None,
    result: QuizResult | None = None,
    wr: WeaknessReport | None = None,
) -> str:
    """Build a Markdown report string suitable for st.download_button."""
    lines: list[str] = []

    # Title
    file_label = ", ".join(quiz_set.file_ids) if quiz_set else "Unknown"
    lines.append(f"# Quiz Report — {file_label}")
    lines.append("")

    # Score
    if result:
        score = result.score
        max_score = result.max_score or float(result.total)
        pct = round(100 * score / max(max_score, 1))
        lines.append(f"**Score:** {_format_points(score)} / {_format_points(max_score)} ({pct}%)")
        lines.append("")

    # Weakness Report
    if wr and (wr.weaknesses or wr.strengths):
        lines.append("## Weakness Report")
        gen_note = " (AI diagnosis)" if wr.generated_by == "llm" else " (By topic)"
        lines.append(f"*Generated by: {wr.generated_by}{gen_note}*")
        lines.append("")
        for w in wr.weaknesses:
            lines.append(f"### ⚠️ {w.topic} — {w.error_count} error(s)")
            lines.append(w.diagnosis)
            lines.append("")
            if w.review_pages:
                lines.append("**Review pages:**")
                for rp in w.review_pages:
                    lines.append(f"- {rp.source_file}, page {rp.page_number}")
                lines.append("")
        for s in wr.strengths:
            lines.append(f"### ✅ {s.topic} — all correct")
            lines.append(s.diagnosis)
            lines.append("")
        lines.append("---")
        lines.append("")

    # Per-question details
    if result and result.details:
        questions = question_by_id(quiz_set.questions) if quiz_set else {}
        lines.append("## Questions")
        for i, d in enumerate(result.details, start=1):
            icon = quiz_result_icon(d)
            qtype = getattr(d, "question_type", "mcq") or "mcq"
            lines.append(f"### {icon} Q{i} [{_question_type_label(qtype)}]: {d.question}")
            question = questions.get(d.question_id)
            lines.append(f"- Your answer: **{format_quiz_answer(question, d.user_answer)}**")
            if d.correct_option:
                correct = format_quiz_answer(question, d.correct_option)
                lines.append(f"- {_correct_answer_label(qtype)}: **{correct}**")
            if d.points_awarded is not None:
                lines.append(f"- Score: **{_format_points(d.points_awarded)} / {_format_points(d.max_points)}**")
            if d.grading_feedback:
                lines.append(f"- Feedback: {d.grading_feedback}")
            if d.explanation:
                lines.append(f"- {d.explanation}")
            if d.wrong_reason:
                lines.append(f"- 💡 {d.wrong_reason}")
            if d.citations:
                lines.append("- Sources:")
                for c in d.citations:
                    lines.append(f"  - {c.source_file}, page {c.page_number}: {c.snippet_reference[:100]}")
            lines.append("")

    return "\n".join(lines)
